function extractJson(text: string): any | null {
  if (!text) return null;
  const start = text.indexOf("{");
  if (start < 0) return null;
  let depth = 0, inStr = false, esc = false;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === "\\") esc = true;
      else if (c === '"') inStr = false;
    } else {
      if (c === '"') inStr = true;
      else if (c === "{") depth++;
      else if (c === "}") { depth--; if (depth === 0) {
        const slice = text.slice(start, i + 1);
        try { return JSON.parse(slice); } catch { return null; }
      } }
    }
  }
  return null;
}

/** Call the model, preferring the deep-research tier but falling back to the
 *  default model if that task is disabled (returns ""). An optional
 *  provider+model override lets a caller run the agent on a specific model
 *  (e.g. GLM-5.2 via the DashScope/qwen provider). */
async function llm(
  prompt: string,
  maxTokens: number,
  gen: { provider?: any; model?: string } = {},
  task: TaskTag = "assistant_chat",
): Promise<string> {
  if (gen.provider || gen.model) {
    return generate(prompt, { ...gen, json: true, maxTokens, temperature: 0.2 });
  }
  // The persona's tier (doc 28 phase 5). An explicit provider/model override
  // still wins, so a user picking a model is not second-guessed.
  return generate(prompt, { task, json: true, maxTokens, temperature: 0.2 });
}



/**
 * Record one event, if there is a conversation to record it against.
 *
 * Deliberately swallowing: the log is an account of the run, never a
 * precondition for it. A failed append degrades to a warning and the assistant
 * carries on — the same contract lib/matching/outcome-events.ts uses for its
 * telemetry.
 */
async function logEvent(
  chatId: string | undefined,
  actorId: string | null,
  event: Parameters<typeof appendEvents>[2][number],
  onEvent?: RunAssistantOpts["onEvent"],
): Promise<void> {
  let seq: number | null = null;
  if (chatId) {
    try { seq = (await appendEvents(chatId, actorId, [event]))[0]?.seq ?? null; }
    catch (e) { console.warn("[assistant log]", (e as Error)?.message); }
  }
  // Streaming is a view of the run, not a participant in it.
  try { onEvent?.({ kind: event.kind, payload: event.payload ?? {}, seq }); }
  catch (e) { console.warn("[assistant stream]", (e as Error)?.message); }
}

export interface RunAssistantOpts {
  maxSteps?: number;
  userId?: string;
  imageRefs?: Array<{ id: string; name: string; base64: string }>;
  provider?: string;
  model?: string;
  /** Telemetry only, forwarded to every model call this run makes (doc 30). The
   *  route sets "request" when a user picked the model; nothing here reads it. */
  resolution?: AiResolution;
  requestedModel?: string;
  /** What is asking (doc 31). Carried to every model call in the run so a
   *  surface pointed elsewhere by config moves the whole run, not its first step. */
  surface?: SurfaceName;
  persona?: Persona | null;
  /** Narrows the belt further; intersected with the persona scope, never a widening. */
  toolAllowlist?: readonly string[];
  /**
   * The conversation to log tool activity against (doc 28 phase 3). When absent
   * nothing is logged and the run is unchanged — the loop must not depend on
   * having a chat, and a first turn has not created one yet.
   */
  chatId?: string;
  /**
   * Called as each event happens, for a caller streaming the run (doc 28 §4.1).
   * Fires whether or not there is a chat to persist to, so a first turn still
   * streams; `seq` is null when the event was not written.
   *
   * Never awaited and never allowed to fail the run: a consumer that throws or
   * blocks must not change what the assistant does.
   */
  onEvent?: (e: { kind: ChatEventKind; payload: Record<string, any>; seq: number | null }) => void;
}

/**
 * The native tool-calling loop (doc 29 phase 5, doc 34).
 *
 * Structurally the same run as the JSON loop — same tools, same policy, same
 * events, same artifacts — with three differences:
 *
 *   1. **The prompt carries no tool catalogue.** The tools travel as schemas on
 *      the request instead of as prose in every step, which is the permanent
 *      token saving this phase is for, and it grows with every tool added.
 *   2. **Arguments are schema-validated by the provider**, so a malformed call is
 *      rare and hard rather than common and soft. That inverts the error
 *      handling: an invalid argument is a bug in the call and surfaces as
 *      `tool.failed`, not as an observation the model is invited to route around
 *      (doc 34 §1.3).
 *   3. **State is a message thread**, not a flattened transcript string.
 *
 * What is deliberately identical: `executeTool` still runs `canUseTool` and
 * `validateToolInput` — a JSON Schema bounds shape, never authority — tool
 * output is still fenced as untrusted, and `tool.requested` is still logged
 * before the work happens so a run that dies mid-tool leaves something to resume
 * from (doc 28 §4.1).
 */
async function runNativeLoop(a: {
  userTask: string;
  tools: Record<string, ToolDef>;
  principal: AiPrincipal;
  opts: RunAssistantOpts;
  gen: Record<string, unknown>;
  modelTask: TaskTag;
  maxSteps: number;
  personaBlock: string;
  steps: AssistantStep[];
  artifacts: ToolArtifact[];
}): Promise<AssistantResult | null> {
  const { tools, principal, opts, gen, modelTask, maxSteps, personaBlock, steps, artifacts } = a;

  const specs: ToolSpec[] = Object.entries(tools).map(([name, def]) => ({
    name,
    // The human-readable parameter hint stays in the description: the schema says
    // what shape is legal, the hint says what the field means.
    description: `${def.description}${def.params ? `\nParameters: ${def.params}` : ""}`,
    inputSchema: inputSchemaFor(name),
  }));

  const messages: ToolThreadMessage[] = [
    { role: "system", content: SYSTEM + personaBlock + `\n\n${DB_SCHEMA_NOTE}\n` },
    { role: "user", content: a.userTask },
  ];

  for (let i = 0; i < maxSteps; i++) {
    checkAiBudget();
    const res = await generateWithTools(messages, specs, { ...gen, provider: gen.provider as any, task: modelTask, maxTokens: 800 });

    if (!res.toolCalls.length && !res.text) {
      // Nothing came back at all. On the FIRST turn this is most likely a model
      // that does not really emit structured tool calls — the catalogue flag is
      // hand-maintained and can drift, and three DashScope models were measured
      // doing exactly this (doc 34 §9). Falling back to the JSON loop is strictly
      // better than answering "unavailable": that path needs no tool support.
      // Later in the run there is already work in `steps`, so restarting would
      // repeat tool calls that have side effects — say so instead.
      if (i === 0) return null;
      return failedRun(takeFailure(), steps, artifacts);
    }
    if (!res.toolCalls.length) {
      return { answer: res.text || "I wasn't able to produce a result.", steps, artifacts, provider: "ok" };
    }

    // The model's turn, verbatim, so the thread stays coherent for the next one.
    messages.push({
      role: "assistant",
      content: res.toolCalls.map((c) => ({
        type: "tool-call" as const, toolCallId: c.id, toolName: c.name, input: c.input,
      })),
    });

    for (const call of res.toolCalls) {
      await logEvent(opts.chatId, principal.userId, {
        kind: "tool.requested", payload: { name: call.name, input: call.input, step: i + 1 },
      }, opts.onEvent);

      let output: string;
      try {
        // executeTool re-checks authority and input regardless of the schema.
        const r = await executeTool(principal, call.name, call.input, opts.imageRefs);
        const files = r.artifacts ?? (r.artifact ? [r.artifact] : []);
        const step: AssistantStep = { tool: call.name, input: call.input, observation: r.observation, report: r.report };
        if (files.length) { step.artifact = files[0]; artifacts.push(...files); }
        steps.push(step);
        await logEvent(opts.chatId, principal.userId, {
          kind: "tool.completed",
          payload: { name: call.name, observation: r.observation.slice(0, 4000), artifacts: files.length },
        }, opts.onEvent);
        // Fenced exactly as the JSON transcript fences it: tool output is data
        // the model reads, never instructions it obeys.
        output = JSON.stringify({ UNTRUSTED_TOOL_DATA: { observation: r.observation.slice(0, 18000), files } });
      } catch (e: any) {
        const err = `Tool ${call.name} failed: ${e?.message ?? "error"}`;
        steps.push({ tool: call.name, input: call.input, error: err });
        await logEvent(opts.chatId, principal.userId, {
          kind: "tool.failed", payload: { name: call.name, error: err },
        }, opts.onEvent);
        output = JSON.stringify({ error: err });
      }

      messages.push({
        role: "tool",
        content: [{ type: "tool-result" as const, toolCallId: call.id, toolName: call.name,
                    output: { type: "text" as const, value: output } }],
      });
    }
  }

  // Step budget spent with tools still running: synthesize from what happened,
  // the same close the JSON loop makes.
  messages.push({ role: "user", content: "Write the final answer for the user now, from the results above. Mention files using only exact /api/artifacts/... links returned by tools." });
  const final = await generateWithTools(messages, [], { ...gen, provider: gen.provider as any, task: modelTask, maxTokens: 800 });
  return { answer: final.text || "I wasn't able to produce a result.", steps, artifacts, provider: "ok" };
}

async function runAssistantLoop(
  userTask: string,
  opts: RunAssistantOpts = {},
): Promise<AssistantResult> {
  if (!currentAiContext()) return withAiContext(await requireAiPrincipal(), () => runAssistantLoop(userTask, opts));
  const bound = currentAiContext()!.principal;
  // What the user actually said and uploaded, so a tool can check a value against it rather
  // than trust the model's claim that "the deck says so" (match_investors: location).
  currentAiContext()!.sourceText = userTask;
  const principal = opts.toolAllowlist ? {...bound,allowedTools:opts.toolAllowlist.filter(name=>!bound.allowedTools || bound.allowedTools.includes(name))} : bound;
  opts = {...opts,userId:principal.userId,persona:principal.persona};
  const maxSteps = Math.max(1, Math.min(Number.isFinite(opts.maxSteps) ? Math.floor(opts.maxSteps!) : 6, 10));
  // Carries the provenance too, so every call in a multi-step run is attributed
  // to the rule that chose the model rather than only the first (doc 30).
  const gen = { provider: opts.provider, model: opts.model, resolution: opts.resolution, requestedModel: opts.requestedModel, surface: opts.surface };
  const modelTask = personaModelTask(opts.persona ?? bound.persona);
  // Persona agent: adapt the system prompt to Founder / VC / LP and the Anker
  // features integrated for the server-resolved persona.
  const personaBlock = opts.persona !== undefined ? personaSystemBlock(opts.persona) : "";
  // Persona preset scopes the tool belt (shared core + persona specialists).
  const tools = toolsFor(principal);
  const steps: AssistantStep[] = [];
  const artifacts: ToolArtifact[] = [];
  const transcript: string[] = [`USER REQUEST: ${userTask}`];

  // Bail early if no request can be attempted at all. Answered from configuration
  // — the task's switch, the provider chain, a credential — with NO model call.
  // This used to send a five-token completion before every message: a billable
  // request on the shared quota, an extra round trip, and a false "unavailable" for
  // any reasoning model that says nothing visible in five tokens (doc 35 #6). What
  // configuration cannot tell us the first real call reports, typed.
  const ready = await aiReadiness({ task: modelTask, provider: gen.provider, surface: opts.surface });
  if (!ready.ok) return failedRun(ready.failure, steps, artifacts);

  // Native tool calling, when the surface is switched on AND the model declares
  // the capability (doc 34 §2.1). Off by default: this phase ships dark, and the
  // switch is the rollback. `tools` here is already toolsFor(principal), so an
  // out-of-scope tool is never offered — not offered, not merely refused.
  const routerCfg = await readRouterConfig().catch(() => null);
  if (nativeToolsEnabled(opts.surface, opts.model ?? null, routerCfg)) {
    const native = await runNativeLoop({
      userTask, tools, principal, opts, gen, modelTask, maxSteps,
      personaBlock, steps, artifacts,
    });
    // null means the native path produced nothing on its first turn; fall through
    // to the JSON loop rather than failing a run a working path could serve.
    if (native) return native;
  }

  let lastSig = "";
  for (let i = 0; i < maxSteps; i++) {
    checkAiBudget();
    const prompt =
      SYSTEM + personaBlock + allToolCatalog(tools) +
      `\n\n${DB_SCHEMA_NOTE}\n` +
      `\n--- transcript so far ---\n${transcript.join("\n")}\n\n` +
      (i === maxSteps - 1 ? `This is your LAST step: reply with {"thought": "...", "final": "..."} now. Report exactly what the tools returned (counts, files) and what is missing.\n\n` : "") +
      `Respond with the next single JSON object now.`;
    // A step carries a thought plus the tool input, and a reasoning model spends tokens before
    // it writes any of it. 800 cut real steps mid-object (doc 36 test, 2026-10-02).
    const raw = await llm(prompt, 1600, gen, modelTask);
    // Nothing came back at all. That is a provider failure and is reported as one —
    // not as "I wasn't able to produce a structured result" with a 200, which is
    // how a mid-run 429 used to read as a finished answer (doc 35 #5).
    if (!raw.trim()) return failedRun(takeFailure(), steps, artifacts);
    // Strict scan first; then the lenient parser, which recovers a step whose object was cut
    // off or slightly malformed.
    const obj = extractJson(raw) ?? extractJsonObject(raw, "assistant-step");

    // A reply that LOOKS like a step but cannot be read is not an answer. It used to be shown
    // verbatim (`{"thought": "…`) and end the run. Ask again instead, a bounded number of times.
    if (!obj && /^\s*(```(?:json)?\s*)?\{\s*"(?:thought|action|final|answer)"/i.test(raw)) {
      steps.push({ thought: "(model reply was not a complete step)", observation: raw.slice(0, 200) });
      transcript.push(`STEP ${i + 1}: your previous reply was not a complete JSON object. Reply with ONE complete JSON object: either {"thought": "...", "action": "<tool_name>", "action_input": {...}} or {"thought": "...", "final": "..."}. Keep "thought" to one short sentence.`);
      continue;
    }

    if (!obj) {
      // Couldn't parse — treat any prose as the final answer.
      const answer = raw.trim();
      steps.push({ thought: "(unstructured model output treated as final)", observation: raw.slice(0, 200) });
      return { answer, steps, artifacts, provider: "ok" };
    }

    if (obj.final || obj.answer) {
      return { answer: String(obj.final ?? obj.answer), steps, artifacts, provider: "ok" };
    }

    const toolName = String(obj.action ?? obj.tool ?? "");
    const input = obj.action_input ?? obj.input ?? obj.args ?? {};
    const tool = tools[toolName];
    if (!tool) {
      const obs = `Unknown tool "${toolName}". Valid tools: ${Object.keys(tools).join(", ")}.`;
      steps.push({ thought: obj.thought, tool: toolName, input, error: obs });
      transcript.push(`STEP ${i + 1}: tried unknown tool "${toolName}". ${obs}`);
      continue;
    }

    // Loop guard: same tool+input twice in a row → stop and synthesize.
    const sig = toolName + JSON.stringify(input);
    if (sig === lastSig) {
      transcript.push(`STEP ${i + 1}: repeated identical call — stopping to synthesize.`);
      break;
    }
    lastSig = sig;

    // The intent is durable before the work happens (doc 28 §4.1). A run that
    // dies between this and tool.completed leaves something to resume from; a
    // run that succeeds leaves an account of what it actually did.
    await logEvent(opts.chatId, principal.userId, {
      kind: "tool.requested", payload: { name: toolName, input, step: i + 1 },
    }, opts.onEvent);

    try {
      const res = await executeTool(principal, toolName, input, opts.imageRefs);
      const step: AssistantStep = { thought: obj.thought, tool: toolName, input, observation: res.observation, report: res.report };
      const files = res.artifacts ?? (res.artifact ? [res.artifact] : []);
      if (files.length) { step.artifact = files[0]; artifacts.push(...files); }
      steps.push(step);
      await logEvent(opts.chatId, principal.userId, {
        kind: "tool.completed",
        // The observation is truncated in the log for the same reason it is in
        // the transcript: a tool can return a great deal, and the log is read.
        payload: { name: toolName, observation: res.observation.slice(0, 4000), artifacts: files.length },
      }, opts.onEvent);
      transcript.push(`STEP ${i + 1}: ${toolName}(${JSON.stringify(input).slice(0, 200)})\nUNTRUSTED TOOL DATA: ${JSON.stringify({observation:res.observation.slice(0,18000),files})}`);
    } catch (e: any) {
      const err = `Tool ${toolName} failed: ${e?.message ?? "error"}`;
      steps.push({ thought: obj.thought, tool: toolName, input, error: err });
      await logEvent(opts.chatId, principal.userId, {
        kind: "tool.failed", payload: { name: toolName, error: err },
      }, opts.onEvent);
      transcript.push(`STEP ${i + 1}: ${err}`);
    }
  }

  // Forced synthesis from the transcript.
  const synth = await llm(
    `You are Anker AI. Based on the transcript below, write a concise final answer for the user. ` +
    `Report only what the tool results above actually returned: counts of firms found and scored, and which file holds them. ` +
    `If you reached fewer results than the user asked for, say how many you have and what is missing; never repeat a requested number as if achieved. ` +
    `Mention files using only exact /api/artifacts/... links returned by tools. Reply as JSON {"final": "..."}.\n\n${transcript.join("\n")}`,
    600, gen, modelTask,
  );
  if (!synth.trim() && !artifacts.length) return failedRun(takeFailure(), steps, artifacts);
  const obj = extractJson(synth);
  const answer = (obj?.final && String(obj.final)) ||
    synth.trim() ||
    (artifacts.length
      ? `Done. Generated: ${artifacts.map((a) => a.url).join(", ")}.`
      : "I gathered information but couldn't finalize a written answer — see the steps above.");
  return { answer, steps, artifacts, provider: "ok" };
}


/**
 * Run the assistant and record the outcome.
 *
 * A thin wrapper over the loop so that `message.assistant` and `run.ended` are
 * emitted from ONE place: the loop returns from several points (final answer,
 * unstructured output, forced synthesis), and instrumenting each was how one of
 * them would eventually be missed.
 */
export async function runAssistant(
  userTask: string,
  opts: RunAssistantOpts = {},
): Promise<AssistantResult> {
  let result: AssistantResult
  try {
    result = await runAssistantLoop(userTask, opts)
  } catch (e) {
    // A run stopped by its cost ceiling is not an error in the system; it is the
    // ceiling working (doc 33 acceptance 2). Reported as its own reason so an
    // operator reading the log can tell "we capped this" from "this broke", and
    // carrying the figures so they do not have to go looking for them.
    const budget = e instanceof AiBudgetExceeded
      ? { reason: "budget" as const, spentUsd: Number(e.spentUsd.toFixed(6)), limitUsd: e.limitUsd, error: e.message }
      : { reason: "error" as const, error: (e as Error)?.message ?? "error" }
    await logEvent(opts.chatId, opts.userId ?? null, {
      kind: "run.ended", payload: budget,
    }, opts.onEvent)
    throw e
  }
  // The tools' verified summaries go on the answer here, once, before it is logged, so a saved
  // conversation shows what the user saw.
  if (result.provider === "ok") result = { ...result, answer: appendReports(result.answer, result.steps), artifacts: keepLatestArtifacts(result.artifacts, result.steps) }
  await logEvent(opts.chatId, opts.userId ?? null, {
    kind: "message.assistant", payload: { content: result.answer },
  }, opts.onEvent)
  // The run's own cost, on the event that closes it. `unpricedCalls` travels with
  // it because a spend of 0 across 5 unpriced calls and a genuine 0 are different
  // facts and must not read the same (doc 33 §1.3).
  const spent = currentRunBudget()
  await logEvent(opts.chatId, opts.userId ?? null, {
    kind: "run.ended",
    payload: {
      reason: "done", steps: result.steps.length, artifacts: result.artifacts.length,
      ...(spent ? { spentUsd: Number(spent.spendUsd.toFixed(6)), unpricedCalls: spent.unpricedCalls } : {}),
    },
  }, opts.onEvent)
  return result
}
