const FAVORITES = ["1578553502586563829","1574946838718935914"]

const community = (k) => `https://www.figma.com/community/file/${k}`

console.log(`Seeding ${POOL.length} templates (${SHORTLISTED.length} shortlisted, ${FAVORITES.length} favorites)…`)

let inserted = 0, updated = 0
for (const key of POOL) {
  const isShort = SHORTLISTED.includes(key)
  const isFav = FAVORITES.includes(key)
  const rows = await sql`
    insert into deck_templates (file_key, community_url, source, shortlisted, favorite)
    values (${key}, ${community(key)}, 'community', ${isShort}, ${isFav})
    on conflict (file_key) do update set
      community_url = excluded.community_url,
      shortlisted   = excluded.shortlisted or deck_templates.shortlisted,
      favorite      = excluded.favorite    or deck_templates.favorite
    returning (xmax = 0) as inserted`
  if (rows[0]?.inserted) inserted++; else updated++
}

const cnt = await sql`
  SELECT
    (SELECT COUNT(*) FROM deck_templates)                     AS total,
    (SELECT COUNT(*) FROM deck_templates WHERE shortlisted)   AS shortlisted,
    (SELECT COUNT(*) FROM deck_templates WHERE favorite)      AS favorite,
    (SELECT COUNT(*) FROM deck_templates WHERE deck_type != 'unclassified') AS classified`
