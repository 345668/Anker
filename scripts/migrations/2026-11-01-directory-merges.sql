-- Directory identity E2 to E4 (docs/architecture/55): reversible merges, aliases, hierarchy. Additive; idempotent. Changes no directory data by itself: nothing merges until a person decides.
CREATE TABLE IF NOT EXISTS directory_merges (
  id            BIGSERIAL PRIMARY KEY,
  kind          TEXT NOT NULL CHECK (kind IN ('firm', 'person')),
  survivor_id   TEXT NOT NULL,
  loser_id      TEXT NOT NULL,
  candidate_id  BIGINT,
  by_staff      TEXT NOT NULL,                       -- a staff email or 'auto' (the flagged automatic merge of certain people)
  reason        TEXT,
  filled        TEXT[] NOT NULL DEFAULT '{}',         -- names of survivor fields that were empty and were filled from the loser (never values)
  before        JSONB NOT NULL DEFAULT '{}'::jsonb,   -- the survivor's values of exactly those fields before the merge (so an undo can put them back)
  conflicts     JSONB NOT NULL DEFAULT '[]'::jsonb,   -- field names where both had different values; the survivor's was kept
  repointed     JSONB NOT NULL DEFAULT '{}'::jsonb,   -- "table.column": ids of the rows that were moved to the survivor
  dropped       JSONB NOT NULL DEFAULT '{}'::jsonb,   -- "table": how many derived rows of the loser were removed (they are regenerated by the next run)
  loser_row     JSONB NOT NULL,                       -- the whole loser row, so an undo restores it exactly
  undo_until    TIMESTAMPTZ NOT NULL,
  undone_at     TIMESTAMPTZ,
  undone_by     TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS directory_merges_survivor_idx ON directory_merges (kind, survivor_id);
CREATE UNIQUE INDEX IF NOT EXISTS directory_merges_loser_live_uq ON directory_merges (kind, loser_id) WHERE undone_at IS NULL;

-- "Old id X now means Y": a saved link, a stale reference or an import still lands on the right record.
CREATE TABLE IF NOT EXISTS directory_aliases (
  kind        TEXT NOT NULL CHECK (kind IN ('firm', 'person')),
  old_id      TEXT NOT NULL,
  new_id      TEXT NOT NULL,
  merge_id    BIGINT NOT NULL REFERENCES directory_merges(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (kind, old_id)
);
CREATE INDEX IF NOT EXISTS directory_aliases_new_idx ON directory_aliases (kind, new_id);

-- What an importer matches on (a name key, a website host, an email, a profile), pointing at the survivor, so a row for a merged record lands on it instead of creating a second one.
CREATE TABLE IF NOT EXISTS directory_alias_keys (
  kind        TEXT NOT NULL CHECK (kind IN ('firm', 'person')),
  key_type    TEXT NOT NULL,
  key         TEXT NOT NULL,
  target_id   TEXT NOT NULL,
  merge_id    BIGINT NOT NULL REFERENCES directory_merges(id),
  PRIMARY KEY (kind, key_type, key)
);
CREATE INDEX IF NOT EXISTS directory_alias_keys_merge_idx ON directory_alias_keys (merge_id);

-- One level of hierarchy: a parent brand with its programmes (docs/architecture/55 section 4).
ALTER TABLE investment_firms ADD COLUMN IF NOT EXISTS parent_firm_id TEXT;
CREATE INDEX IF NOT EXISTS investment_firms_parent_idx ON investment_firms (parent_firm_id) WHERE parent_firm_id IS NOT NULL;
